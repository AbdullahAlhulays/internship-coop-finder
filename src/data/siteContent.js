export function getSitePageDefinition(slug) {
  return sitePages.find((page) => page.slug === slug) ?? null;
}

export function getLocalizedSitePage(slug, locale = "en") {
  const definition = getSitePageDefinition(slug);

  return definition ? definition[locale] ?? definition.en : null;
}
